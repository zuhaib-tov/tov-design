// Generates src/lib/watch/page-map.ts: change-tracking page key -> doc page route and title.
// Runs automatically before `dev` and `build` so the Overview card can say which page a Figma change affects.
const fs = require("fs");
const path = require("path");

const navSrc = fs.readFileSync("src/lib/nav.ts", "utf8");
const titles = {};
for (const m of navSrc.matchAll(/label:\s*"([^"]+)",\s*href:\s*"([^"]+)"/g)) titles[m[2]] = m[1];

const walk = (d) =>
  fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]));

const map = {};
for (const f of walk("src/app").sort()) {
  const parts = f.split(path.sep);
  if (path.basename(f) !== "page.tsx" || parts.includes("api") || parts.includes("gate")) continue;
  const rel = path.relative("src/app", path.dirname(f)).split(path.sep).join("/");
  const route = rel === "" ? "/" : "/" + rel;
  const src = fs.readFileSync(f, "utf8");
  for (const m of src.matchAll(/ChangeLogTable[^>]*page="([^"]+)"/g)) {
    if (!map[m[1]]) map[m[1]] = { route, title: titles[route] || route };
  }
}

const body = Object.entries(map)
  .map(([key, v]) => `  ${JSON.stringify(key)}: { route: ${JSON.stringify(v.route)}, title: ${JSON.stringify(v.title)} },`)
  .join("\n");
const out = `// Generated by scripts/gen-page-map.cjs — do not edit by hand.\nexport const PAGE_MAP: Record<string, { route: string; title: string }> = {\n${body}\n};\n`;
fs.writeFileSync("src/lib/watch/page-map.ts", out);
console.log("page map entries:", Object.keys(map).length);
